-- رقميات: قاعدة البيانات السحابية (Supabase / PostgreSQL)
-- نفّذ كامل هذا الملف من Supabase > SQL Editor > New query

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'موظف',
  role text not null default 'employee' check (role in ('admin','employee')),
  created_at timestamptz not null default now()
);

create table if not exists public.items (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('screen','protector')),
  model text not null,
  alternative text not null,
  notes text not null default '',
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.create_profile_for_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email,'@',1)),
    'employee'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.create_profile_for_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.items enable row level security;

drop policy if exists "profiles read own" on public.profiles;
create policy "profiles read own" on public.profiles
for select to authenticated using (id = auth.uid() or public.is_admin());

drop policy if exists "authenticated read items" on public.items;
create policy "authenticated read items" on public.items
for select to authenticated using (true);

drop policy if exists "admins insert items" on public.items;
create policy "admins insert items" on public.items
for insert to authenticated with check (public.is_admin() and created_by = auth.uid());

drop policy if exists "admins update items" on public.items;
create policy "admins update items" on public.items
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins delete items" on public.items;
create policy "admins delete items" on public.items
for delete to authenticated using (public.is_admin());

